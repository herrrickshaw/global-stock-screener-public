def _approx_equal(a, b, path="") -> None:
    if isinstance(a, dict):
        assert set(a) == set(b), path
        for k in a:
            _approx_equal(a[k], b[k], f"{path}/{k}")
    elif isinstance(a, list):
        assert len(a) == len(b), path
        for i, (x, y) in enumerate(zip(a, b)):
            _approx_equal(x, y, f"{path}[{i}]")
    elif isinstance(a, float) and isinstance(b, float):
        assert a == pytest.approx(b, rel=1e-9, nan_ok=True), path
    else:
        assert a == b, path


def test_snapshot_matches_pre_refactor_golden():
    expected = json.loads(GOLDEN.read_text())
    actual = json.loads(json.dumps(build_snapshot(), sort_keys=True, default=str))
    _approx_equal(expected, actual)


def test_high_52w_falls_back_to_close_without_high_column():
    df = mk(1)[["Close"]]
    assert high_52w(df) == float(df["Close"].tail(252).max())


def test_prior_avg_volume_excludes_latest_bar_and_needs_history():
    df = mk(2, n=30)
    assert prior_avg_volume(df, 20) == float(df["Volume"].iloc[-21:-1].mean())
    assert prior_avg_volume(df.tail(20), 20) is None
    assert prior_avg_volume(df.drop(columns="Volume"), 20) is None


def test_run_all_swallows_a_failing_strategy(monkeypatch):
    import strategies

    def boom(_):
        raise RuntimeError("bad data")

    monkeypatch.setattr(strategies.garp, "screen", boom)
    res = run_all(StockData("X", "US", ohlcv=mk(3), fundamentals={"net_income": 1, "roa": 0.1}))
    assert "garp" not in res and "piotroski" in res


def test_unknown_screen_operator_raises():
    with pytest.raises(ValueError):
        custom_screener.evaluate(StockData("X", ohlcv=mk(4)), {"ltp": ("~", 1)})


def test_median_turnover_usd_applies_rate_and_unit():
    df = pd.DataFrame({"Close": [10.0] * 25, "Volume": [100.0] * 25})
    assert liquidity.median_turnover_usd(df, rate=2.0, unit=1.0) == 500.0
    assert liquidity.median_turnover_usd(df, rate=2.0, unit=100.0) == 5.0
    assert liquidity.median_turnover_usd(df.head(10), rate=2.0) is None
    assert liquidity.median_turnover_usd(df.assign(Volume=0.0), rate=2.0) is None


def test_build_index_with_injected_loader_and_fx(tmp_path):
    data = {"US": {"AAA": mk(5), "TINY": mk(6, n=10)}, "UK": {"BBB": mk(7)}, "IN": {"CCC": mk(8)}}
    out = tmp_path / "idx.parquet"
    idx = liquidity.build_index(
        verbose=False,
        loader=lambda m: data[m],
        fx={"USD": 1.0, "GBP": 0.5, "INR": None},  # INR has no rate -> market skipped
        markets=["US", "UK", "IN"],
        out_path=out,
    )
    assert sorted(idx["Symbol"]) == ["AAA", "BBB"]
    assert out.exists() and len(pd.read_parquet(out)) == 2
    uk = idx[idx["Symbol"] == "BBB"].iloc[0]
    expected = float((data["UK"]["BBB"]["Close"] * data["UK"]["BBB"]["Volume"]).tail(20).median())
    assert uk["turnover_usd"] == pytest.approx((expected / 100.0) / 0.5)  # pence unit, GBP rate


