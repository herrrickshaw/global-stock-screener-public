def test_to_long_round_trip_and_int32_volume():
    hist = {"A": mk(1, n=50), "B": mk(2, n=50)}
    lg = frames.to_long(hist)
    assert str(lg["Volume"].dtype) == "int32" and str(lg["Close"].dtype) == "float32"
    back = frames.long_to_dict(lg)
    assert set(back) == {"A", "B"}
    assert np.allclose(back["A"]["Close"], hist["A"]["Close"], rtol=1e-5)


def test_write_and_read_seed_in_tmp(tmp_path):
    p = tmp_path / "s" / "seed.parquet"
    assert frames.write_seed({"A": mk(1, n=50)}, p) == 1
    assert list(frames.read_seed(p)) == ["A"]
    assert frames.recompress_seed(tmp_path / "missing.parquet")["error"] == "missing"
